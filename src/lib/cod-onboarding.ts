/** Подтверждение после успешного прохождения обоих вопросов. */
export function formatOnboardingComplete(displayName: string, activisionTag: string): string {
  return `✅ Готово, ${displayName}! Тег «${activisionTag}» сохранён — будете в ежедневной сводке по играм, как только у бота появится рабочий доступ к статистике.`;
}

const MAX_ANSWER_LENGTH = 100;

/** Не пусто и не длиннее разумного предела (чтобы кто-то не прислал
 * вместо имени простыню текста, которая потом некрасиво отобразится в
 * ежедневной сводке) -- чистая синтаксическая проверка, НЕ проверка
 * формата самого тега (см. isWellFormedActivisionTag ниже для этого). */
export function isValidAnswerText(text: string): boolean {
  const trimmed = text.trim();
  return trimmed.length > 0 && trimmed.length <= MAX_ANSWER_LENGTH;
}

/** Примерная проверка формата тега -- "что угодно, потом #, потом хотя
 * бы одна цифра", по образцу данного владельцем примера
 * "亗 Casper#7378333". Намеренно МЯГКАЯ: Activision-теги могут содержать
 * практически любые символы в части до "#" (включая эмодзи/нестандартные
 * символы, как в самом примере владельца, где тег начинается с «亗»), так
 * что эта проверка ловит только явно отсутствующий разделитель "#" или
 * отсутствие цифр после него -- не настоящую валидацию против
 * Activision, которая здесь недоступна (нет сети на этом шаге, и сама
 * проверка существования тега происходит только при попытке получить
 * статистику, см. cod-client.ts). Намеренно не отклоняет ничего строже
 * этого, чтобы не блокировать онбординг настоящим участникам из-за
 * слишком строгой локальной догадки о формате. */
export function looksLikeActivisionTag(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed.includes("#")) return false;
  const afterHash = trimmed.slice(trimmed.lastIndexOf("#") + 1);
  return /\d/.test(afterHash);
}

