import type { ChannelFlag } from "../db.js";

/**
 * Подпись каждого тумблера Модерации — ОДНА таблица и для самой кнопки
 * (toggleButtonLabel в telegram.ts), и для текста всплывающего
 * подтверждения (toggleConfirmationText ниже), чтобы они никогда не
 * разошлись друг с другом при будущих правках.
 */
export const CHANNEL_FLAG_LABELS: Record<ChannelFlag, string> = {
  auto_pin: "Автозакрепление",
  auto_unpin: "Автооткрепление",
  welcome_enabled: "Приветствие новых участников",
  spam_filter_enabled: "Проверка спама",
  leave_enabled: "Уведомление о выходе",
  antilink_enabled: "АнтиСсылка",
  url_blacklist_enabled: "Чёрный список ссылок",
  hide_service_messages: "Скрывать системные «вступил/покинул»",
  cod_summary_enabled: "Ежедневная сводка",
};

/**
 * Текст всплывающего уведомления Telegram (answerCallbackQuery) сразу
 * после нажатия тумблера — see
 * https://core.telegram.org/bots/api#answercallbackquery.
 *
 * До этого единственным сигналом об успехе была перерисовка значка ✅/❌
 * на самой кнопке, которую легко не заметить среди других кнопок на
 * экране — отсюда и жалоба "не знаю, сработало ли нажатие вообще".
 * Теперь каждый тумблер в боте явно отвечает на callback_query текстом с
 * новым состоянием, независимо от того, заметил ли человек изменение
 * значка на кнопке.
 */
export function toggleConfirmationText(flag: ChannelFlag, enabled: boolean): string {
  return `${enabled ? "✅" : "❌"} ${CHANNEL_FLAG_LABELS[flag]}: ${enabled ? "включено" : "выключено"}`;
}

/**
 * Текст предупреждения для экрана Модерации, когда у бота подтверждённо
 * НЕТ права Telegram «Удалять сообщения» в чате (can_delete_messages) —
 * права, без которого hide_service_messages/АнтиСсылка/чёрный список
 * ссылок могут быть честно включены в базе данных, но физически не
 * удаляют ничего (Telegram тихо отклоняет deleteMessage без этого
 * права).
 *
 * Пустая строка для true (право подтверждённо есть) и для null
 * (проверка самого права не удалась — бот уже не в чате, временная
 * ошибка сети и т.п. — это ДЕЙСТВИТЕЛЬНО неизвестно, а не "права нет", и
 * показывать тревогу в этом случае значило бы солгать о том, чего мы не
 * проверяли).
 */
export function buildBotDeletePermissionWarning(canDeleteMessages: boolean | null): string {
  if (canDeleteMessages !== false) return "";
  return (
    "⚠️ У бота НЕТ права «Удалять сообщения» в этой группе — скрытие системных уведомлений, АнтиСсылка и " +
    "чёрный список ссылок ничего не будут удалять, пока администратор группы не выдаст боту это право " +
    "(Управление группой → Администраторы → этот бот → Удаление сообщений).\n\n"
  );
}
